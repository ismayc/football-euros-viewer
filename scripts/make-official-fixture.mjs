// Regenerates test/fixtures/official-kickoffs.js — the authoritative fixture the
// committed schedule is tested against.
//
// The point of the fixture is that it comes from a DIFFERENT source than the one
// that built src/data/matches.js. The builder (scripts/fetch-tournament.mjs)
// takes its structure and kickoff instants from ESPN; this takes them from
// OpenFootball's public-domain Euro file, which publishes the local (CEST) time
// and the host city as UEFA stated them. test/data.test.js then asserts the two
// independently-sourced views of the same tournament agree — so a silent shift
// in either feed fails the build instead of quietly rewriting history.
//
// Node built-ins only.
//
//   node scripts/make-official-fixture.mjs

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OPENFOOTBALL = 'https://raw.githubusercontent.com/openfootball/euro.json/master/2024/euro.json'

// OpenFootball writes host cities in German; the app (following ESPN and UEFA's
// English-language material) uses the English exonyms for two of them.
const CITY = { München: 'Munich', Köln: 'Cologne' }
const ALIASES = { 'Czech Republic': 'Czechia', Turkey: 'Türkiye' }
const canon = (n) => ALIASES[n] || n

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const res = await fetch(OPENFOOTBALL)
if (!res.ok) throw new Error(`OpenFootball fetch failed: HTTP ${res.status}`)
const doc = await res.json()
const matches = doc.matches || []
if (matches.length !== 51) throw new Error(`Expected 51 matches, got ${matches.length}`)

// Key each record by (date, sorted team pair) — the same join the builder uses,
// and the only stable key the Euro file offers (it carries no match numbers).
const rows = matches.map((m) => ({
  key: `${m.date}|${[canon(m.team1), canon(m.team2)].sort().join('|')}`,
  cest: `${m.date} ${m.time}`,
  city: CITY[m.ground] || m.ground,
  group: m.group ? m.group.replace('Group ', '') : null,
  round: m.round,
}))

const groups = {}
for (const m of matches) {
  if (!m.group) continue
  const g = m.group.replace('Group ', '')
  groups[g] ??= new Set()
  groups[g].add(canon(m.team1))
  groups[g].add(canon(m.team2))
}

const lines = [
  `// GENERATED by scripts/make-official-fixture.mjs — do not edit by hand.`,
  `//`,
  `// Authoritative kickoff time, host city and group for every match of UEFA Euro`,
  `// 2024, keyed by kickoff date + team pair and stated in CEST ('YYYY-MM-DD HH:mm',`,
  `// 24h) — the timezone UEFA published the fixture list in.`,
  `//`,
  `// Source: OpenFootball's public-domain euro.json (2024). This is deliberately a`,
  `// DIFFERENT source from the one that builds src/data/matches.js (ESPN), so`,
  `// test/data.test.js comparing them is a real cross-check rather than a`,
  `// restatement. If the two ever disagree, one of the feeds has moved and the`,
  `// disagreement is the finding — do not "fix" it by editing this file alone.`,
  `//`,
  `// Regenerate with: npm run fixture:official`,
  ``,
  `export const OFFICIAL_CEST = {`,
  ...rows.map((r) => `  ${q(r.key)}: ${q(r.cest)},`),
  `}`,
  ``,
  `export const OFFICIAL_CITY = {`,
  ...rows.map((r) => `  ${q(r.key)}: ${q(r.city)},`),
  `}`,
  ``,
  `export const OFFICIAL_GROUPS = {`,
  ...Object.keys(groups)
    .sort()
    .map((g) => `  ${g}: [${[...groups[g]].sort().map(q).join(', ')}],`),
  `}`,
  ``,
  `// Round label per match, as OpenFootball states it.`,
  `export const OFFICIAL_ROUND = {`,
  ...rows.map((r) => `  ${q(r.key)}: ${q(r.round)},`),
  `}`,
  ``,
]

const path = join(ROOT, 'test/fixtures/official-kickoffs.js')
writeFileSync(path, lines.join('\n'))
console.log(`✓ ${matches.length} matches, ${Object.keys(groups).length} groups → ${path}`)
